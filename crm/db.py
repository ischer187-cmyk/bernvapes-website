def _split_sql(sql):
    parts, buf, q = [], [], False
    for ch in sql:
        if ch == "'":
            q = not q
            buf.append(ch)
        elif ch == ';' and not q:
            stmt = ''.join(buf).strip()
            if stmt:
                parts.append(stmt)
            buf = []
        else:
            buf.append(ch)
    tail = ''.join(buf).strip()
    if tail:
        parts.append(tail)
    return parts

class SqliteConn:
    pg = False
    def __init__(self, path):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        self.raw = sqlite3.connect(path, timeout=30)
        self.raw.row_factory = sqlite3.Row
        self.raw.execute('pragma foreign_keys=on')
    def execute(self, sql, params=()):
        try:
            cur = self.raw.execute(sql, params)
        except sqlite3.IntegrityError as e:
            raise IntegrityError(str(e)) from e
        rows = []
        last = cur.lastrowid
        if cur.description:
            cols = [d[0] for d in cur.description]
            rows = [Row(cols, tuple(r)) for r in cur.fetchall()]
        return Result(rows, last, cur.rowcount)
    def executescript(self, sql):
        self.raw.executescript(sql)
    def commit(self):
        self.raw.commit()
    def rollback(self):
        self.raw.rollback()
    def close(self):
        if self.raw is not None:
            self.raw.close()
            self.raw = None

class PgConn:
    pg = True
    def __init__(self, url):
        import psycopg
        self.raw = psycopg.connect(url)
        self._psycopg = psycopg
    def execute(self, sql, params=()):
        sql2 = translate(sql, True)
        try:
            cur = self.raw.execute(sql2, params)
        except self._psycopg.errors.IntegrityError as e:
            raise IntegrityError(str(e)) from e
        rows, last = [], None
        if cur.description:
            cols = [d.name for d in cur.description]
            fetched = cur.fetchall()
            rows = [Row(cols, tuple(r)) for r in fetched]
            if re.match(r'\s*insert\b', sql2, re.I) and rows:
                last = rows[0][0]
        rc = len(rows) if re.match(r'\s*insert\b', sql2, re.I) else (cur.rowcount if cur.rowcount is not None else len(rows))
        if re.match(r'\s*insert\b', sql2, re.I):
            rc = 1 if rows else 0
        return Result(rows, last, rc)
    def executescript(self, sql):
        for stmt in _split_sql(sql):
            self.raw.execute(stmt)
    def commit(self):
        self.raw.commit()
    def rollback(self):
        self.raw.rollback()
    def close(self):
        if self.raw is not None:
            self.raw.close()
            self.raw = None

def database_url():
    return (os.environ.get('DATABASE_URL') or '').strip()

def sqlite_path():
    return os.environ.get('CRM_SQLITE_PATH') or str(ROOT / 'crm.db')

def connect():
    url = database_url()
    if url.startswith('postgres://') or url.startswith('postgresql://'):
        conn = PgConn(url)
    else:
        conn = SqliteConn(sqlite_path())
    bucket = _REQUEST_CONNS.get()
    if bucket is not None:
        bucket.append(conn)
    return conn

def begin_request():
    return _REQUEST_CONNS.set([])

def end_request(token):
    for conn in _REQUEST_CONNS.get() or []:
        try:
            conn.close()
        except Exception:
            pass
    _REQUEST_CONNS.reset(token)
