"""SQLite by default. PostgreSQL only when DATABASE_URL starts with postgres."""
import contextvars, os, re, sqlite3
from pathlib import Path

_REQUEST_CONNS = contextvars.ContextVar('crm_request_conns', default=None)

ROOT = Path(__file__).resolve().parent

class IntegrityError(Exception):
    pass

class Row(tuple):
    def __new__(cls, cols, vals):
        return super().__new__(cls, tuple(vals))
    def __init__(self, cols, vals):
        self._map = {c: vals[i] for i, c in enumerate(cols)}
    def __getitem__(self, k):
        if isinstance(k, str):
            return self._map[k]
        return tuple.__getitem__(self, k)
    def keys(self):
        return self._map.keys()
    def get(self, k, default=None):
        return self._map.get(k, default)

class Result:
    def __init__(self, rows, lastrowid, rowcount):
        self._rows = rows
        self.lastrowid = lastrowid
        self.rowcount = rowcount
    def fetchone(self):
        return self._rows[0] if self._rows else None
    def fetchall(self):
        return list(self._rows)
    def __iter__(self):
        return iter(self._rows)

def translate(sql, pg=True):
    """Turn the SQLite statements this app uses into PostgreSQL."""
    if not pg:
        return sql
    ignore = bool(re.search(r'insert\s+or\s+ignore', sql, re.I))
    s = re.sub(r'insert\s+or\s+ignore', 'INSERT', sql, count=1, flags=re.I)
    s = re.sub(
        r"datetime\(\s*'now'\s*\)",
        "to_char((clock_timestamp() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')",
        s, flags=re.I)
    s = re.sub(r'\bcollate\s+nocase\b', '', s, flags=re.I)
    out = []
    q = False
    for ch in s:
        if ch == "'":
            q = not q
            out.append(ch)
        elif ch == '?' and not q:
            out.append('%s')
        else:
            out.append(ch)
    s = ''.join(out)
    if ignore:
        s = s.rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'
    if re.match(r'\s*insert\b', s, re.I) and 'returning' not in s.lower():
        s = s.rstrip().rstrip(';') + ' RETURNING id'
    return s

def adapt_schema_pg(sql):
    lines = []
    for ln in sql.splitlines():
        if ln.strip().upper().startswith('PRAGMA'):
            continue
        lines.append(ln)
    s = '\n'.join(lines)
    s = re.sub(
        r'\bid\s+integer\s+primary\s+key\b',
        'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
        s, flags=re.I)
    s = re.sub(
        r'DEFAULT\s+CURRENT_TIMESTAMP',
        "DEFAULT to_char((clock_timestamp() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')",
        s, flags=re.I)
    return s

